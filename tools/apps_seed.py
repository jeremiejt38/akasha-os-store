"""Seed data for the Akasha OS Store catalogue.

Each record produces one ``apps/<id>/manifest.json`` via ``tools/seed_apps.py``.
Icon sources are hints consumed by ``tools/fetch_icons.py`` (they are NOT
written into the manifest; the manifest keeps ``"icon": "icon.png"``).
"""

KODI_MIRROR = "https://mirrors.kodi.tv/addons/omega/"

LEGAL_KODI = (
    "Addon officiel du depot Kodi (Omega). {extra}Aucun contenu redistribue "
    "par akasha-os-store."
)
LEGAL_EXT = (
    "{extra}Fiche informative uniquement : installation enregistree comme "
    "lanceur web (Chromium), pas d'installation Kodi automatique en V1. "
    "Aucun contenu redistribue par akasha-os-store."
)


def kodi(addon_id, extra=""):
    return {
        "install": {
            "type": "kodi-repo",
            "source_url": KODI_MIRROR,
            "addon_id": addon_id,
        },
        "legal": LEGAL_KODI.format(extra=extra),
    }


def ext(url, deep_link=None, extra=""):
    return {
        "install": {"type": "external-app", "source_url": url},
        "deep_link": deep_link,
        "legal": LEGAL_EXT.format(extra=extra),
    }


